import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { ncRadonZones } from '../lib/radonData.js';

// This conversion exposes already-vendored public Census boundaries to the
// isolated wireframe. No requests, source-data modifications, or simplification.
const root = new URL('../', import.meta.url);
const countySource = JSON.parse(await readFile(new URL('lib/data/ncCounties.json', root), 'utf8'));
const districtSource = JSON.parse(await readFile(new URL('lib/data/nc08District.json', root), 'utf8'));
const clean = (value) => typeof value === 'string' ? value.replaceAll('\u2014', ',') : value;
const rings = (geometry) => geometry.type === 'MultiPolygon' ? geometry.coordinates.flat() : geometry.coordinates;
function center(geometry) {
  const ring = rings(geometry).reduce((largest, next) => next.length > largest.length ? next : largest, []);
  let area = 0, x = 0, y = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [ax, ay] = ring[i], [bx, by] = ring[i + 1];
    const cross = ax * by - bx * ay;
    area += cross; x += (ax + bx) * cross; y += (ay + by) * cross;
  }
  return Math.abs(area) > 1e-9 ? [Number((x / (3 * area)).toFixed(5)), Number((y / (3 * area)).toFixed(5))] : ring[0];
}
const output = {
  source: clean(countySource.source),
  retrieved: countySource.retrieved,
  district_source: clean(districtSource.source),
  district_retrieved: districtSource.retrieved,
  note: 'Real Census boundaries. Observation markers in this review are fictional sample data.',
  counties: countySource.counties.map((county) => ({ ...county, center: center(county.geometry) })),
  district: { ...districtSource.nc08, center: center(districtSource.nc08.geometry) },
};
const destination = new URL('public/data/map-preview-geography.json', root);
await mkdir(new URL('public/data/', root), { recursive: true });
await writeFile(destination, `${JSON.stringify(output)}\n`, 'utf8');
const radonPoints = output.counties.map(county => {
  const zone = ncRadonZones[county.name];
  if (![1, 2, 3].includes(zone)) throw new Error(`Missing zone for ${county.name}`);
  return { id: county.name, name: county.name, lng: county.center[0], lat: county.center[1], zone, severity: ({ 1: 'high', 2: 'elevated', 3: 'good' })[zone] };
}).sort((a, b) => a.name.localeCompare(b.name));
await writeFile(new URL('lib/frontend/map-radon-fixture.ts', root), `// Generated by scripts/build-map-preview-geography.mjs.\n// Existing static county potential zones, not home measurements.\nimport type { MapPoint } from '@/components/map-preview/MapCanvas';\n\nexport const radonPoints: MapPoint[] = ${JSON.stringify(radonPoints, null, 2)};\n`, 'utf8');
console.log(`Prepared ${output.counties.length} Census counties and NC-08 in ${fileURLToPath(destination)}`);
